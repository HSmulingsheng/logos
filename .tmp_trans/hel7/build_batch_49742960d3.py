def main():
    with open(IN_PATH, encoding="utf-8") as f:
        src = json.load(f)
    if len(src) != len(ZH):
        sys.exit("count mismatch: %d items vs %d translations" % (len(src), len(ZH)))
    out = []
    for item, zh in zip(src, ZH):
        assert isinstance(zh, str) and zh.strip(), item["k"]
        out.append({"k": item["k"], "zh": zh})
    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w", encoding="utf-8") as f:
        json.dump(out, f, ensure_ascii=False, indent=1)
    # verify
    with open(OUT_PATH, encoding="utf-8") as f:
        chk = json.load(f)
    assert [x["k"] for x in chk] == [x["k"] for x in src], "key order mismatch"
    assert len(chk) == len(src)
    print("OK items=%d keys=%d" % (len(src), len(chk)))
    print("first key:", chk[0]["k"])
    raw = open(OUT_PATH, encoding="utf-8").read()
    assert "\\u" not in raw, "escaped unicode present"
    print("bytes:", len(raw.encode("utf-8")))


if __name__ == "__main__":
    main()
